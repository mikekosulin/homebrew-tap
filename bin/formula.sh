#!/usr/bin/env bash
# The Homebrew formula of a release, from its SHA256SUMS:
#
#   bin/formula.sh v0.3.0 SHA256SUMS > Formula/kanareika.rb
#
# .github/workflows/update.yml runs it for the latest kanareika release and commits Formula/kanareika.rb, so
# `brew install mikekosulin/tap/kanareika` installs the release binary. Windows has no Homebrew.
set -euo pipefail
tag="$1" sums="$2"
version="${tag#v}"
sha() { awk -v f="kanareika-$1" '$2 == f { print $1 }' "$sums" | grep . || { echo "no $1 in $sums" >&2; exit 1; }; }
base="https://github.com/mikekosulin/kanareika/releases/download/$tag"
cat <<RB
# Generated by bin/formula.sh for $tag (.github/workflows/update.yml); do not edit by hand.
class Kanareika < Formula
  desc "Agentless read-only security audit of servers over SSH"
  homepage "https://github.com/mikekosulin/kanareika"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/kanareika-darwin-arm64"
      sha256 "$(sha darwin-arm64)"
    end
    on_intel do
      url "$base/kanareika-darwin-amd64"
      sha256 "$(sha darwin-amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$base/kanareika-linux-arm64"
      sha256 "$(sha linux-arm64)"
    end
    on_intel do
      url "$base/kanareika-linux-amd64"
      sha256 "$(sha linux-amd64)"
    end
  end

  def install
    bin.install Dir["kanareika-*"].first => "kanareika"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/kanareika --version")
  end
end
RB
